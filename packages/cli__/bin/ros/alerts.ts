// Alert system for `ros`.
//
// `ros alerts install` generates a self-contained bash script and installs
// it on each target server with a cron entry. The script monitors Docker
// containers (health, cpu, mem, disk, stopped, oom) AND host resources
// (cpu, mem, disk) and sends alerts via email and/or webhook.
//
// Webhook payload schema (unified):
//   { event, source, metric, threshold, value, container, mount,
//     subject, body, host, timestamp }

import type { AlertFilter } from "./types.ts"

export const ALERT_SCRIPT_PATH = "/usr/local/bin/ros-alerts.sh"
export const ALERT_CRON_NAME = "ros-alerts"
export const ALERT_STATE_PATH = "/var/lib/ros/alerts.state"

export interface AlertsConfig {
  schedule?: string
  email?: string
  webhook?: string | { url: string; headers?: Record<string, string>; secret?: string }
  filters?: AlertFilter[]
}

export const DEFAULT_FILTERS: AlertFilter[] = [
  { name: "Container unhealthy", type: "health", duration: "1m" },
  { name: "Container stopped", type: "stopped", duration: "30s" },
  { name: "Container high CPU", type: "cpu", threshold: 90, duration: "5m" },
  { name: "Container high memory", type: "mem", threshold: 90, duration: "5m" },
  { name: "Container OOM killed", type: "oom", duration: "0s" },
]

const BASH = "\u0001BASH\u0001"

export function renderAlertScript(cfg: AlertsConfig): string {
  const schedule = cfg.schedule ?? "*/5 * * * *"
  const filters =
    cfg.filters && cfg.filters.length > 0 ? cfg.filters : DEFAULT_FILTERS
  const activeFilters = filters.filter((f) => f.enabled !== false)
  const email = cfg.email ?? ""

  let webhook = ""
  let webhookSecret = ""
  if (typeof cfg.webhook === "string") {
    webhook = cfg.webhook
  } else if (cfg.webhook) {
    webhook = cfg.webhook.url
    webhookSecret = cfg.webhook.secret ?? ""
  }

  const lines: string[] = []
  lines.push("#!/usr/bin/env bash")
  lines.push("# Auto-generated by `ros alerts install`. Do not edit by hand.")
  lines.push("# Schedule: " + schedule)
  lines.push("")
  lines.push("set -u")
  lines.push("")
  lines.push("EMAIL=" + q(email))
  lines.push("WEBHOOK=" + q(webhook))
  lines.push("WEBHOOK_SECRET=" + q(webhookSecret))
  lines.push("STATE_FILE=" + q(ALERT_STATE_PATH))
  lines.push("")
  lines.push('mkdir -p "$(dirname "$STATE_FILE")"')
  lines.push('touch "$STATE_FILE"')
  lines.push("")
  lines.push(
    'DOCKER_PS=$(docker ps --no-trunc --format "{{.ID}}|{{.Names}}|{{.Status}}" 2>/dev/null)',
  )
  lines.push(
    'DOCKER_INSPECT=$(docker ps -a --no-trunc --format "{{.ID}}|{{.Names}}|{{.State.Status}}|{{.State.OOMKilled}}|{{.State.StartedAt}}" 2>/dev/null)',
  )
  lines.push(
    'DOCKER_STATS=$(docker stats --no-stream --no-trunc --format "{{.ID}}|{{.Name}}|{{.CPUPerc}}|{{.MemPerc}}" 2>/dev/null)',
  )
  lines.push("")
  lines.push("# ---- helpers ----")
  lines.push('log() { echo "[ros-alerts] $*" >&2; }')
  lines.push("")
  lines.push("to_epoch() {")
  lines.push('  date -u -d "$1" +%s 2>/dev/null || echo 0')
  lines.push("}")
  lines.push("")
  lines.push("to_seconds() {")
  lines.push('  case "$1" in')
  lines.push("    *s) echo " + BASH + "1%s" + BASH + " ;;")
  lines.push("    *m) echo $(( " + BASH + "1%m" + BASH + " * 60 )) ;;")
  lines.push("    *h) echo $(( " + BASH + "1%h" + BASH + " * 3600 )) ;;")
  lines.push('    0|""|*) echo 0 ;;')
  lines.push("  esac")
  lines.push("}")
  lines.push("")
  // send_alert: unified payload with source/metric/threshold/value/container/mount
  lines.push("send_alert() {")
  lines.push('  local source="$1"      # "host" or "container"')
  lines.push('  local metric="$2"      # cpu | mem | disk | unhealthy | stopped | oom')
  lines.push('  local threshold="$3"   # threshold value (may be empty)')
  lines.push('  local value="$4"       # current measured value (may be empty)')
  lines.push('  local container="$5"   # container name (empty for host)')
  lines.push('  local mount="$6"       # mount point (empty unless disk)')
  lines.push('  local subject="$7"')
  lines.push("  local curl_args=()")
  lines.push('  local body="$8"')
  lines.push("  local timestamp")
  lines.push('  timestamp=$(date -u +%Y-%m-%dT%H:%M:%SZ)')
  lines.push("")
  lines.push('  if [ -n "$EMAIL" ]; then')
  lines.push("    {")
  lines.push('      echo "Subject: [ros-alert] $subject"')
  lines.push('      echo "To: $EMAIL"')
  lines.push('      echo "Date: $timestamp"')
  lines.push("      echo")
  lines.push('      echo "$body"')
  lines.push('    } | sendmail -t 2>/dev/null || log "sendmail failed for $subject"')
  lines.push("  fi")
  lines.push("")
  lines.push('  if [ -n "$WEBHOOK" ]; then')
  lines.push("    local payload")
  // Unified payload: { event, source, metric, threshold, value, container, mount, subject, body, host, timestamp }
  lines.push(
    '    payload=$(printf \'%s\' "{\\"event\\":\\"alert.fired\\",\\"source\\":\\"$source\\",\\"metric\\":\\"$metric\\",\\"threshold\\":\\"$threshold\\",\\"value\\":\\"$value\\",\\"container\\":\\"$container\\",\\"mount\\":\\"$mount\\",\\"subject\\":\\"$subject\\",\\"body\\":\\"$body\\",\\"timestamp\\":\\"$timestamp\\",\\"host\\":\\"$(hostname)\\"}")',
  )
  lines.push('    local signature=""')
  lines.push('    if [ -n "$WEBHOOK_SECRET" ]; then')
  lines.push(
    "      signature=$(printf '%s' \"$payload\" | openssl dgst -sha256 -hmac \"$WEBHOOK_SECRET\" -hex | awk '{print $2}')",
  )
  lines.push("    fi")

  const customHeaders =
    typeof cfg.webhook === "object" && cfg.webhook?.headers
      ? Object.entries(cfg.webhook.headers)
      : []
  for (const [k, v] of customHeaders) {
    lines.push('    curl_args+=(-H ' + q(k + ": " + v) + ")")
  }

  lines.push('    curl -sS -X POST -H \'Content-Type: application/json\' \\')
  lines.push("      " + BASH + 'signature:+-H "X-Ros-Signature: sha256=$signature"}' + BASH + " \\")
  lines.push(
    '      "$${curl_args[@]:-}" -d "$payload" "$WEBHOOK" >/dev/null 2>&1 || log "webhook failed for $subject"',
  )
  lines.push("  fi")
  lines.push("}")
  lines.push("")
  lines.push("# Debounce: only fire if not already fired in the last 5 min for the same key.")
  lines.push("should_fire() {")
  lines.push('  local key="$1"')
  lines.push("  local now")
  lines.push("  now=$(date +%s)")
  lines.push("  local last")
  lines.push(
    '  last=$(grep -F "|$key|" "$STATE_FILE" 2>/dev/null | tail -1 | cut -d\'|\' -f1)',
  )
  lines.push('  if [ -z "$last" ] || [ $((now - last)) -gt 300 ]; then')
  lines.push(
    '    grep -v "|$key|" "$STATE_FILE" > "$STATE_FILE.tmp" 2>/dev/null || true',
  )
  lines.push('    mv "$STATE_FILE.tmp" "$STATE_FILE" 2>/dev/null || true')
  lines.push('    echo "$now|$key|" >> "$STATE_FILE"')
  lines.push("    return 0")
  lines.push("  fi")
  lines.push("  return 1")
  lines.push("}")
  lines.push("")

  for (const f of activeFilters) {
    lines.push(renderFilter(f))
    lines.push("")
  }

  lines.push('log "tick done"')

  let out = lines.join("\n")
  out = out.split(BASH + "1%s" + BASH).join("${1%s}")
  out = out.split(BASH + "1%m" + BASH).join("${1%m}")
  out = out.split(BASH + "1%h" + BASH).join("${1%h}")
  out = out
    .split(BASH + 'signature:+-H "X-Ros-Signature: sha256=$signature"}' + BASH)
    .join('${signature:+-H "X-Ros-Signature: sha256=$signature"}')
  return out
}

function q(s: string): string {
  if (s === "") return '""'
  return "'" + s.replace(/'/g, "'\\''") + "'"
}

function renderFilter(f: AlertFilter): string {
  const name = f.name
  const ctr = f.container ?? "*"
  const dur = f.duration ?? "0s"
  const th = f.threshold ?? 0
  // Resolve source. cpu/mem/disk can be host or container; health/stopped/oom always container.
  const source = f.source ?? (["health", "stopped", "oom"].includes(f.type) ? "container" : "container")

  const out: string[] = []
  out.push("# " + name + " (" + f.type + ", source=" + source + ")")

  switch (f.type) {
    // ── Container-only filters ──────────────────────────────────
    case "health":
      out.push('while IFS="|" read -r id name status; do')
      out.push('  [ -z "$id" ] && continue')
      out.push('  case "$name" in ' + ctr + ") ;; *) continue ;; esac")
      out.push('  case "$status" in')
      out.push('    *"(unhealthy)"*)')
      out.push('      key="health|$name"')
      out.push('      if should_fire "$key"; then')
      out.push('        send_alert "container" "unhealthy" "" "" "$name" "" "Unhealthy: $name" "Container $name is unhealthy on $(hostname): $status"')
      out.push("      fi")
      out.push("      ;;")
      out.push("  esac")
      out.push('done <<< "$DOCKER_PS"')
      break

    case "stopped":
      out.push('while IFS="|" read -r id name state oom started; do')
      out.push('  [ -z "$id" ] && continue')
      out.push('  case "$name" in ' + ctr + ") ;; *) continue ;; esac")
      out.push('  case "$state" in')
      out.push("    exited|dead)")
      out.push('      if [ -n "$started" ]; then')
      out.push('        sec=$(( $(date +%s) - $(to_epoch "$started") ))')
      out.push("        threshold=$(to_seconds " + q(dur) + ")")
      out.push('        if [ "$sec" -lt "$threshold" ]; then continue; fi')
      out.push("      fi")
      out.push('      key="stopped|$name"')
      out.push('      if should_fire "$key"; then')
      out.push('        send_alert "container" "stopped" "" "" "$name" "" "Stopped: $name" "Container $name is $state on $(hostname)"')
      out.push("      fi")
      out.push("      ;;")
      out.push("  esac")
      out.push('done <<< "$DOCKER_INSPECT"')
      break

    case "oom":
      out.push('while IFS="|" read -r id name state oom started; do')
      out.push('  [ -z "$id" ] && continue')
      out.push('  case "$name" in ' + ctr + ") ;; *) continue ;; esac")
      out.push('  if [ "$oom" = "true" ]; then')
      out.push('    key="oom|$name"')
      out.push('    if should_fire "$key"; then')
      out.push('      send_alert "container" "oom" "" "" "$name" "" "OOM killed: $name" "Container $name was OOM-killed on $(hostname)"')
      out.push("    fi")
      out.push("  fi")
      out.push('done <<< "$DOCKER_INSPECT"')
      break

    // ── Shared filters (host or container based on `source`) ────
    case "cpu":
      if (source === "host") {
        out.push("# Host CPU: /proc/stat")
        out.push('read cpu user nice system idle iowait irq softirq steal guest < /proc/stat')
        out.push("sleep 1")
        out.push('read cpu user2 nice2 system2 idle2 iowait2 irq2 softirq2 steal2 guest2 < /proc/stat')
        out.push("total1=$((user+nice+system+idle+iowait+irq+softirq+steal))")
        out.push("total2=$((user2+nice2+system2+idle2+iowait2+irq2+softirq2+steal2))")
        out.push("dt=$((total2-total1))")
        out.push("di=$((idle2-idle1))")
        out.push("cpu_pct=0")
        out.push('if [ "$dt" -gt 0 ]; then')
        out.push('  cpu_pct=$(awk -v d="$dt" -v i="$di" \'BEGIN { printf "%d", 100*(d-i)/d }\')')
        out.push("fi")
        out.push('if [ "$cpu_pct" -ge ' + th + " ]; then")
        out.push('  key="host_cpu"')
        out.push('  if should_fire "$key"; then')
        out.push('    send_alert "host" "cpu" "' + th + '" "$cpu_pct" "" "" "Host CPU: $cpu_pct%" "Host $(hostname) CPU at ${cpu_pct}% (threshold ' + th + '%)"')
        out.push("  fi")
        out.push("fi")
      } else {
        // Container CPU from docker stats
        out.push('while IFS="|" read -r id name cpu mem; do')
        out.push('  [ -z "$id" ] && continue')
        out.push('  case "$name" in ' + ctr + ") ;; *) continue ;; esac")
        out.push('  cpu_num=${cpu%%%}')
        out.push('  cpu_int=${cpu_num%.*}')
        out.push('  [ -z "$cpu_int" ] && cpu_int=0')
        out.push('  if [ "$cpu_int" -ge ' + th + " ]; then")
        out.push('    key="cpu|$name"')
        out.push('    if should_fire "$key"; then')
        out.push('      send_alert "container" "cpu" "' + th + '" "$cpu_int" "$name" "" "CPU: $name" "Container $name at $cpu on $(hostname)"')
        out.push("    fi")
        out.push("  fi")
        out.push('done <<< "$DOCKER_STATS"')
      }
      break

    case "mem":
      if (source === "host") {
        out.push("# Host memory: /proc/meminfo")
        out.push("mem_total=$(awk '/MemTotal/ {print $2}' /proc/meminfo)")
        out.push("mem_avail=$(awk '/MemAvailable/ {print $2}' /proc/meminfo)")
        out.push("mem_pct=0")
        out.push('if [ "$mem_total" -gt 0 ]; then')
        out.push('  mem_pct=$(awk -v t="$mem_total" -v a="$mem_avail" \'BEGIN { printf "%d", 100*(t-a)/t }\')')
        out.push("fi")
        out.push('if [ "$mem_pct" -ge ' + th + " ]; then")
        out.push('  key="host_mem"')
        out.push('  if should_fire "$key"; then')
        out.push('    send_alert "host" "mem" "' + th + '" "$mem_pct" "" "" "Host memory: $mem_pct%" "Host $(hostname) memory at ${mem_pct}% (threshold ' + th + '%)"')
        out.push("  fi")
        out.push("fi")
      } else {
        // Container memory from docker stats
        out.push('while IFS="|" read -r id name cpu mem; do')
        out.push('  [ -z "$id" ] && continue')
        out.push('  case "$name" in ' + ctr + ") ;; *) continue ;; esac")
        out.push('  mem_num=${mem%%%}')
        out.push('  mem_int=${mem_num%.*}')
        out.push('  [ -z "$mem_int" ] && mem_int=0')
        out.push('  if [ "$mem_int" -ge ' + th + " ]; then")
        out.push('    key="mem|$name"')
        out.push('    if should_fire "$key"; then')
        out.push('      send_alert "container" "mem" "' + th + '" "$mem_int" "$name" "" "Memory: $name" "Container $name at $mem on $(hostname)"')
        out.push("    fi")
        out.push("  fi")
        out.push('done <<< "$DOCKER_STATS"')
      }
      break

    case "disk":
      // Disk is always host-level
      const mnt = f.mount ?? ""
      if (mnt) {
        out.push("# Host disk: single mount")
        out.push('pct=$(df --output=pcent ' + q(mnt) + " 2>/dev/null | tail -1 | tr -d ' %' || echo 0)")
        out.push('if [ "$pct" -ge ' + th + " ]; then")
        out.push('  key="disk|' + mnt + '"')
        out.push('  if should_fire "$key"; then')
        out.push('    send_alert "host" "disk" "' + th + '" "$pct" "" "' + mnt + '" "Disk ' + mnt + ': $pct%" "Mount ' + mnt + ' at ${pct}% on $(hostname) (threshold ' + th + '%)"')
        out.push("  fi")
        out.push("fi")
      } else {
        out.push("# Host disk: all mounts")
        out.push("df --output=target,pcent 2>/dev/null | tail -n +2 | while read mnt pct_raw; do")
        out.push('  pct=$(echo "$pct_raw" | tr -d " %" || echo 0)')
        out.push('  [ "$pct" -lt ' + th + " ] && continue")
        out.push('  key="disk|$mnt"')
        out.push('  if should_fire "$key"; then')
        out.push('    send_alert "host" "disk" "' + th + '" "$pct" "" "$mnt" "Disk $mnt: $pct%" "Mount $mnt at ${pct}% on $(hostname) (threshold ' + th + '%)"')
        out.push("  fi")
        out.push("done")
      }
      break

    default:
      out.push("# unknown filter type: " + (f as any).type)
  }
  return out.join("\n")
}

export function renderCronFile(schedule: string): string {
  return (
    schedule +
    " root " +
    ALERT_SCRIPT_PATH +
    " >/var/log/ros-alerts.log 2>&1\n"
  )
}
