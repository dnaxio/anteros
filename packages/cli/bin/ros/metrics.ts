// Metrics scraper generator.
//
// `ros metrics install` generates a self-contained bash script and
// installs it on each target server. The script collects host and
// container metrics and POSTs them as JSON (NDJSON) to a configured
// endpoint.
//
// Output schema (one JSON object per line, NDJSON):
//
//   Host memory:
//     {"source":"host","metric":"mem","host":"srv-1","ts":"2024-06-24T08:32:00Z","total":8589934592,"usage":4294967296,"pct":50.0}
//
//   Host CPU:
//     {"source":"host","metric":"cpu","host":"srv-1","ts":"2024-06-24T08:32:00Z","total":8000,"usage":1880,"pct":23.5}
//
//   Host disk (one per mount point):
//     {"source":"host","metric":"disk","host":"srv-1","ts":"2024-06-24T08:32:00Z","mount":"/","total":52428800000,"usage":26214400000,"pct":50.0}
//
//   Container memory:
//     {"source":"container","metric":"mem","host":"srv-1","ts":"2024-06-24T08:32:00Z","container":"dnx-api","total":1073741824,"usage":134217728,"pct":12.5}
//
//   Container CPU:
//     {"source":"container","metric":"cpu","host":"srv-1","ts":"2024-06-24T08:32:00Z","container":"dnx-api","total":1000,"usage":37,"pct":3.7}
//
// Units:
//   - mem   total/usage: bytes
//   - cpu   total/usage: millicores (1 core = 1000)
//   - disk  total/usage: bytes
//   - pct:  percentage (0-100, two decimals)
//
// For container metrics, `total` reflects the configured limit
// (cpus/memory on the pod). If no limit is set, the host's total is
// used as the reference, and `pct` represents the share of host
// capacity the container is using.

import type { MetricsTarget } from "./types.ts"

export const METRICS_SCRIPT_PATH = "/usr/local/bin/ros-metrics.sh"
export const METRICS_CRON_NAME = "ros-metrics"
export const METRICS_LOG_PATH = "/var/log/ros-metrics.log"

export interface MetricsConfig {
  schedule?: string
  endpoint: string | MetricsTarget
  include_host?: boolean
  include_disk?: boolean
  include_containers?: boolean
  labels?: Record<string, string>
}

export function normalizeMetricsConfig(
  raw:
    | string
    | { url: string; headers?: Record<string, string>; secret?: string }
    | undefined,
): { url: string; headers: Record<string, string>; secret?: string } | undefined {
  if (!raw) return undefined
  if (typeof raw === "string") {
    return { url: raw, headers: {} }
  }
  return {
    url: raw.url,
    headers: raw.headers ?? {},
    secret: raw.secret,
  }
}

export function renderMetricsScript(cfg: MetricsConfig, hostname: string): string {
  const schedule = cfg.schedule ?? "* * * * *"
  const normalized = normalizeMetricsConfig(cfg.endpoint)
  if (!normalized) {
    throw new Error("metrics.endpoint is required")
  }
  const endpoint = normalized.url
  const customHeaders = normalized.headers
  const webhookSecret = normalized.secret ?? ""
  const includeHost = cfg.include_host !== false
  const includeDisk = cfg.include_disk !== false
  const includeContainers = cfg.include_containers !== false
  const extraLabelsJson = formatJsonLabels(cfg.labels ?? {})

  // Serialize custom headers as a bash array
  const headerLines: string[] = []
  for (const [k, v] of Object.entries(customHeaders)) {
    headerLines.push("  curl_args+=(-H " + q(k + ": " + v) + ")")
  }
  const secretLine = webhookSecret
    ? "WEBHOOK_SECRET=" + q(webhookSecret)
    : "WEBHOOK_SECRET=" + q("")

  // Build the collection blocks conditionally
  const blocks: string[] = []
  if (includeHost) {
    blocks.push(hostBlock(hostname))
  }
  if (includeDisk) {
    blocks.push(diskBlock(hostname))
  }
  if (includeContainers) {
    blocks.push(containersBlock(hostname))
  }

  const lines: string[] = []
  lines.push("#!/usr/bin/env bash")
  lines.push("# Auto-generated by `ros metrics install`. Do not edit by hand.")
  lines.push("# Schedule: " + schedule)
  lines.push("# Endpoint: " + endpoint)
  lines.push("# Host: " + hostname)
  lines.push("")
  lines.push("set -u")
  lines.push("")
  lines.push("ENDPOINT=" + q(endpoint))
  lines.push("LOG_FILE=" + q(METRICS_LOG_PATH))
  lines.push(secretLine)
  lines.push("")
  lines.push("# Custom headers (will be merged in send_payload)")
  lines.push("declare -a curl_args=()")
  for (const h of headerLines) lines.push(h)
  lines.push("")
  lines.push("# Static labels (from config) as a JSON fragment, e.g. ',\"env\":\"prod\"'")
  lines.push("EXTRA_LABELS='" + extraLabelsJson + "'")
  lines.push("")
  lines.push('log() { echo "[ros-metrics] $*" >&2; }')
  lines.push("")
  lines.push("# Send one NDJSON line to the endpoint, with optional HMAC signing.")
  lines.push("send_payload() {")
  lines.push('  local body="$1"')
  lines.push('  local sig=""')
  lines.push('  if [ -n "$WEBHOOK_SECRET" ]; then')
  lines.push('    sig=$(printf \'%s\' "$body" | openssl dgst -sha256 -hmac "$WEBHOOK_SECRET" -hex | awk \'{print $2}\')')
  lines.push("  fi")
  lines.push('  if [ -n "$sig" ]; then')
  lines.push('    curl_args+=(-H "X-Ros-Signature: sha256=$sig")')
  lines.push("  fi")
  lines.push("  curl -sS --max-time 10 -X POST \\")
  lines.push('    -H "Content-Type: application/x-ndjson" \\')
  lines.push('    "${curl_args[@]:-}" \\')
  lines.push('    --data-binary "$body" \\')
  lines.push('    "$ENDPOINT" >/dev/null 2>&1 || log "send failed (status ignored)"')
  lines.push("}")
  lines.push("")
  // Body blocks
  for (const block of blocks) {
    lines.push(block)
    lines.push("")
  }
  lines.push('log "tick done"')
  lines.push("")
  return lines.join("\n")
}

function hostBlock(hostname: string): string {
  return [
    "# --- HOST metrics ---",
    "# Reference for CPU: 1 core = 1000 millicores. Override per host with",
    "# ROS_CPU_TOTAL_MILLICORES (e.g. on a 16-core server: 16000).",
    "CPU_TOTAL_REF=${ROS_CPU_TOTAL_MILLICORES:-8000}",
    "",
    "# CPU: sample /proc/stat twice (1s apart). total in millicores.",
    "read cpu user nice system idle iowait irq softirq steal guest < /proc/stat",
    "sleep 1",
    "read cpu user2 nice2 system2 idle2 iowait2 irq2 softirq2 steal2 guest2 < /proc/stat",
    "total1=$((user+nice+system+idle+iowait+irq+softirq+steal))",
    "total2=$((user2+nice2+system2+idle2+iowait2+irq2+softirq2+steal2))",
    "dt=$((total2-total1))",
    "di=$((idle2-idle1))",
    "cpu_usage=0",
    "cpu_pct=0",
    'if [ "$dt" -gt 0 ]; then',
    '  cpu_usage=$((CPU_TOTAL_REF * (dt - di) / dt))',
    '  cpu_pct=$(awk -v d="$dt" -v i="$di" \'BEGIN { printf "%.2f", 100*(d-i)/d }\')',
    "fi",
    "",
    "# Memory: total in bytes, usage = total - available.",
    "mem_total=$(awk '/MemTotal/ {print $2*1024}' /proc/meminfo)",
    "mem_avail=$(awk '/MemAvailable/ {print $2*1024}' /proc/meminfo)",
    "mem_usage=$((mem_total - mem_avail))",
    "mem_pct=0",
    'if [ "$mem_total" -gt 0 ]; then',
    '  mem_pct=$(awk -v t="$mem_total" -v a="$mem_avail" \'BEGIN { printf "%.2f", 100*(t-a)/t }\')',
    "fi",
    "",
    "# Emit host metrics. All values in raw units + percent.",
    'emit_host() {',
    '  local metric="$1" total="$2" usage="$3" pct="$4"',
    '  local ts',
    '  ts=$(date -u +%Y-%m-%dT%H:%M:%SZ)',
    '  printf \'{"source":"host","metric":"%s","host":"%s","ts":"%s"%s,"total":%s,"usage":%s,"pct":%s}\\n\' \\',
    '    "$metric" "' + hostname + '" "$ts" "$EXTRA_LABELS" "$total" "$usage" "$pct"',
    "}",
    "",
    'emit_host mem "$mem_total" "$mem_usage" "$mem_pct" | send_payload "$(cat)"',
    'emit_host cpu "$CPU_TOTAL_REF" "$cpu_usage" "$cpu_pct" | send_payload "$(cat)"',
    "",
  ].join("\n")
}

function diskBlock(hostname: string): string {
  return [
    "# --- HOST disk metrics (one line per mount point) ---",
    "# total/usage in bytes, pct = usage/total*100.",
    'emit_disk() {',
    '  local mount="$1" total="$2" used="$3" pct="$4"',
    '  local ts',
    '  ts=$(date -u +%Y-%m-%dT%H:%M:%SZ)',
    '  printf \'{"source":"host","metric":"disk","host":"%s","ts":"%s"%s,"mount":"%s","total":%s,"usage":%s,"pct":%s}\\n\' \\',
    '    "' + hostname + '" "$ts" "$EXTRA_LABELS" "$mount" "$total" "$used" "$pct"',
    "}",
    "df -B1 --output=source,size,used,target 2>/dev/null | tail -n +2 | while read src size used mnt; do",
    '  [ -z "$mnt" ] && continue',
    '  [ "$size" -gt 0 ] 2>/dev/null || continue',
    '  pct=$(awk -v s="$size" -v u="$used" \'BEGIN { printf "%.2f", 100*u/s }\')',
    '  emit_disk "$mnt" "$size" "$used" "$pct" | send_payload "$(cat)"',
    "done",
    "",
  ].join("\n")
}

function containersBlock(hostname: string): string {
  return [
    "# --- CONTAINER metrics (one line per container, per metric) ---",
    "# `total` is the configured limit on the container in raw units",
    "# (bytes for mem, millicores for cpu). If no limit is set, the host's",
    "# total is used as the reference, and pct reflects the container's",
    "# share of the host's capacity.",
    "CPU_TOTAL_REF=${ROS_CPU_TOTAL_MILLICORES:-8000}",
    "",
    'emit_container() {',
    '  local metric="$1" container="$2" total="$3" usage="$4" pct="$5"',
    '  local ts',
    '  ts=$(date -u +%Y-%m-%dT%H:%M:%SZ)',
    '  printf \'{"source":"container","metric":"%s","host":"%s","ts":"%s"%s,"container":"%s","total":%s,"usage":%s,"pct":%s}\\n\' \\',
    '    "$metric" "' + hostname + '" "$ts" "$EXTRA_LABELS" "$container" "$total" "$usage" "$pct"',
    "}",
    "",
    "# docker inspect: id|name|cpu_quota|cpu_period|mem_limit",
    "# We compute cpu limit as quota/period*1000 millicores when set.",
    "# memory limit is taken as bytes (or 0 if unset).",
    "INSPECT_FMT='{{.Id}}|{{.Name}}|{{if .HostConfig.CPUQuota}}{{.HostConfig.CPUQuota}}{{else}}0{{end}}|{{if .HostConfig.CPUPeriod}}{{.HostConfig.CPUPeriod}}{{else}}0{{end}}|{{if .HostConfig.Memory}}{{.HostConfig.Memory}}{{else}}0{{end}}'",
    "",
    "# Merge stats (1) + inspect (1) on container id.",
    "STATS=$(docker stats --no-stream --no-trunc --format '{{.ID}} {{.Name}} {{.CPUPerc}} {{.MemPerc}} {{.MemUsage}}' 2>/dev/null)",
    "echo \"$STATS\" | while read id name cpu_perc mem_perc mem_usage; do",
    '  [ -z "$id" ] && continue',
    "  LIMITS=$(docker inspect --format \"$INSPECT_FMT\" \"$id\" 2>/dev/null)",
    "  cpu_quota=$(echo \"$LIMITS\" | awk -F'|' '{print $3}')",
    "  cpu_period=$(echo \"$LIMITS\" | awk -F'|' '{print $4}')",
    "  mem_limit=$(echo \"$LIMITS\" | awk -F'|' '{print $5}')",
    "",
    "  # CPU limit: quota/period * 1000 (millicores). 0 = no limit.",
    "  cpu_total=0",
    '  if [ \"$cpu_quota\" -gt 0 ] && [ \"$cpu_period\" -gt 0 ]; then',
    "    cpu_total=$((cpu_quota * 1000 / cpu_period))",
    "  else",
    "    cpu_total=$CPU_TOTAL_REF",
    "  fi",
    "",
    "  # CPU usage: percent * total / 100",
    "  cpu_num=$(echo \"$cpu_perc\" | tr -d '%' | awk '{ printf \"%.2f\", $1 }')",
    "  cpu_usage=$(awk -v p=\"$cpu_num\" -v t=\"$cpu_total\" 'BEGIN { printf \"%d\", p*t/100 }')",
    "  cpu_pct=\"$cpu_num\"",
    "",
    "  # Memory: usage = current RSS, total = limit (0 if none).",
    "  # mem_usage is like \"456MiB / 1GiB\" — take the first number.",
    "  mem_bytes=$(echo \"$mem_usage\" | awk '{print $1}' | numfmt --from=iec 2>/dev/null || echo 0)",
    "  mem_total=\"$mem_limit\"",
    "  mem_pct=0",
    '  if [ \"$mem_total\" -gt 0 ] 2>/dev/null; then',
    "    mem_pct=$(awk -v u=\"$mem_bytes\" -v t=\"$mem_total\" 'BEGIN { printf \"%.2f\", 100*u/t }')",
    "  else",
    "    # No limit: derive pct from docker's mem_perc directly.",
    "    mem_pct=$(echo \"$mem_perc\" | tr -d '%' | awk '{ printf \"%.2f\", $1 }')",
    "  fi",
    "",
    '  emit_container cpu "$name" "$cpu_total" "$cpu_usage" "$cpu_pct" | send_payload "$(cat)"',
    '  emit_container mem "$name" "$mem_total" "$mem_bytes" "$mem_pct" | send_payload "$(cat)"',
    "done",
    "",
  ].join("\n")
}

export function renderMetricsCronFile(schedule: string): string {
  return (
    schedule +
    " root " +
    METRICS_SCRIPT_PATH +
    " >> " +
    METRICS_LOG_PATH +
    " 2>&1\n"
  )
}

function q(s: string): string {
  if (s === "") return '""'
  return "'" + s.replace(/'/g, "'\\''") + "'"
}

function formatJsonLabels(labels: Record<string, string>): string {
  const parts: string[] = []
  for (const [k, v] of Object.entries(labels)) {
    const escaped = String(v)
      .replace(/\\/g, "\\\\")
      .replace(/"/g, '\\"')
      .replace(/\n/g, "\\n")
    parts.push('"' + k + '":"' + escaped + '"')
  }
  return parts.length > 0 ? "," + parts.join(",") : ""
}
